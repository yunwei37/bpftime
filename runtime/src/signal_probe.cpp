// Scoped fixed fault-PC -> recovery-PC probe-read backend.
//
// The SIGSEGV/SIGBUS disposition is installed only while a protected copy is
// in flight and is restored to the previous disposition afterwards, so the
// process never keeps a bpftime-owned handler outside the copy window. The
// handler recovers exclusively synchronous access faults whose instruction
// pointer is an exact member of the assembly fault table and whose si_code is
// in the supported set; everything else is forwarded to the previous
// disposition with the original siginfo/ucontext.
#include "signal_probe.hpp"

#if BPFTIME_HAVE_SIGNAL_PROBE_BACKEND

#include <cerrno>
#include <cstdint>
#include <mutex>
#include <signal.h>
#include <sys/mman.h>
#include <unistd.h>
extern "C" {
int bpftime_pc_safe_copy_asm(void *dst, const void *src, size_t n);
extern const char bpftime_pc_probe_load[];
extern const char bpftime_pc_probe_store[];
extern const char bpftime_pc_probe_recovery[];
}

namespace
{
std::mutex g_disp_mtx;
uint64_t g_window_depth = 0;
struct sigaction g_prev_segv = {};
struct sigaction g_prev_bus = {};

thread_local bool tls_feasible_cached = false;
thread_local stack_t tls_alt = {};
thread_local bool tls_alt_owned = false;

// fork() may happen while another thread is inside a copy window. The child
// returns from fork() with no copy actually in flight, so its global depth is
// zeroed and the per-thread feasibility cache invalidated (the child signal
// mask is its own; a blocked SIGSEGV/SIGBUS cannot be seen via a stale parent
// cache). The prepare/parent/child trio keeps the disposition mutex owned
// consistently on both sides of the fork.
void atfork_prepare()
{
	g_disp_mtx.lock();
}

void atfork_parent()
{
	g_disp_mtx.unlock();
}

void atfork_child()
{
	g_window_depth = 0;
	tls_feasible_cached = false;
	g_disp_mtx.unlock();
}

const int g_atfork_registration = []() {
	return pthread_atfork(atfork_prepare, atfork_parent, atfork_child);
}();

// Exact membership of the two access instruction PCs. The fixed two-entry
// set is expressed as named symbols rather than an address table so all
// references are RIP-relative and the shared library needs no text
// relocations.
bool is_fault_pc(const char *rip)
{
	return rip == bpftime_pc_probe_load || rip == bpftime_pc_probe_store;
}

// Synchronous access faults generated by the protected load/store. An
// asynchronous SIGSEGV (kill/tkill/queue: SI_USER, SI_TKILL, SI_QUEUE) is
// never in this set and always reaches the previous disposition, even if it
// happened to interrupt a thread at a table PC.
bool is_supported_sicode(int sig, int code)
{
	if (sig == SIGSEGV)
		return code == SEGV_MAPERR || code == SEGV_ACCERR ||
		       code == SI_KERNEL;
	if (sig == SIGBUS)
		return code == BUS_ADRERR || code == BUS_OBJERR;
	return false;
}

// Forward a foreign signal to the previous disposition. Emulates the parts
// of kernel delivery that a direct invocation can preserve; remaining deltas
// (SA_ONSTACK stack choice, SA_RESTART EINTR semantics) are documented in
// signal_probe.hpp rather than silently claimed as identical.
void chain_previous(int sig, siginfo_t *info, void *ctx,
		    const struct sigaction &prev)
{
	if (prev.sa_flags & SA_SIGINFO) {
		sigset_t blocked, saved;
		blocked = prev.sa_mask;
		sigaddset(&blocked, sig);
		pthread_sigmask(SIG_BLOCK, &blocked, &saved);
		if (prev.sa_flags & SA_RESETHAND) {
			struct sigaction dfl = {};
			dfl.sa_handler = SIG_DFL;
			sigaction(sig, &dfl, nullptr);
		}
		prev.sa_sigaction(sig, info, ctx);
		pthread_sigmask(SIG_SETMASK, &saved, nullptr);
		return;
	}
	if (prev.sa_handler == SIG_DFL || prev.sa_handler == SIG_IGN) {
		sigaction(sig, &prev, nullptr);
		raise(sig);
		return;
	}
	sigset_t blocked, saved;
	blocked = prev.sa_mask;
	sigaddset(&blocked, sig);
	pthread_sigmask(SIG_BLOCK, &blocked, &saved);
	if (prev.sa_flags & SA_RESETHAND) {
		struct sigaction dfl = {};
		dfl.sa_handler = SIG_DFL;
		sigaction(sig, &dfl, nullptr);
	}
	prev.sa_handler(sig);
	pthread_sigmask(SIG_SETMASK, &saved, nullptr);
}

void fault_handler(int sig, siginfo_t *info, void *ctx)
{
	auto *uc = static_cast<ucontext_t *>(ctx);
	auto *rip = reinterpret_cast<const char *>(
		uc->uc_mcontext.gregs[REG_RIP]);
	if (is_fault_pc(rip) && is_supported_sicode(sig, info->si_code)) {
		uc->uc_mcontext.gregs[REG_RIP] =
			reinterpret_cast<greg_t>(bpftime_pc_probe_recovery);
		return; // sigreturn restores the interrupted mask/registers
	}
	chain_previous(sig, info, ctx,
		       sig == SIGSEGV ? g_prev_segv : g_prev_bus);
}

// Per-thread, one-time feasibility: an unblocked SIGSEGV/SIGBUS mask plus a
// usable signal stack. A blocked-mask failure is deliberately not cached, so
// the same thread picks the backend up automatically after unblocking.
bool ensure_thread_feasible()
{
	if (tls_feasible_cached)
		return true;
	sigset_t cur;
	if (pthread_sigmask(SIG_SETMASK, nullptr, &cur) != 0 ||
	    sigismember(&cur, SIGSEGV) == 1 ||
	    sigismember(&cur, SIGBUS) == 1)
		return false;
	stack_t existing;
	if (sigaltstack(nullptr, &existing) != 0)
		return false;
	if (existing.ss_flags & SS_DISABLE) {
		const size_t sz = static_cast<size_t>(SIGSTKSZ) + 64 * 1024;
		void *mem = mmap(nullptr, sz, PROT_READ | PROT_WRITE,
				 MAP_PRIVATE | MAP_ANONYMOUS | MAP_STACK, -1,
				 0);
		if (mem == MAP_FAILED)
			return false;
		tls_alt = { mem, 0, sz };
		if (sigaltstack(&tls_alt, nullptr) != 0) {
			munmap(mem, sz);
			return false;
		}
		tls_alt_owned = true;
	}
	tls_feasible_cached = true;
	return true;
}

bool enter_window()
{
	std::lock_guard<std::mutex> guard(g_disp_mtx);
	if (g_window_depth == 0) {
		struct sigaction sa = {};
		sa.sa_sigaction = fault_handler;
		sa.sa_flags = SA_SIGINFO | SA_ONSTACK;
		sigemptyset(&sa.sa_mask);
		bool segv_ok = sigaction(SIGSEGV, &sa, &g_prev_segv) == 0;
		bool bus_ok = sigaction(SIGBUS, &sa, &g_prev_bus) == 0;
		if (!segv_ok || !bus_ok) {
			if (segv_ok)
				sigaction(SIGSEGV, &g_prev_segv, nullptr);
			if (bus_ok)
				sigaction(SIGBUS, &g_prev_bus, nullptr);
			return false;
		}
	}
	++g_window_depth;
	return true;
}

void exit_window()
{
	std::lock_guard<std::mutex> guard(g_disp_mtx);
	if (--g_window_depth == 0) {
		sigaction(SIGSEGV, &g_prev_segv, nullptr);
		sigaction(SIGBUS, &g_prev_bus, nullptr);
	}
}

struct window_guard
{
	bool entered;
	window_guard() noexcept : entered(enter_window()) {}
	~window_guard()
	{
		if (entered)
			exit_window();
	}
	window_guard(const window_guard &) = delete;
	window_guard &operator=(const window_guard &) = delete;
};
} // namespace

namespace bpftime::signal_probe
{
bool backend_available() noexcept
{
	return ensure_thread_feasible();
}

int protected_copy(void *dst, const void *src, size_t n) noexcept
{
	if (n == 0)
		return 1;
	if (!ensure_thread_feasible())
		return -1;
	window_guard guard;
	if (!guard.entered)
		return -1;
	int saved_errno = errno;
	int rc = bpftime_pc_safe_copy_asm(dst, src, n);
	errno = saved_errno;
	return rc;
}
} // namespace bpftime::signal_probe

#endif // BPFTIME_HAVE_SIGNAL_PROBE_BACKEND
